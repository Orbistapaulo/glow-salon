-- Run once in the Supabase SQL Editor: on the test project first, then on live.
-- Adds to the existing schema; nothing the n8n workflows use is renamed.
-- Spec: docs/superpowers/specs/2026-09-24-glow-salon-crm-design.md

begin;

-- =============================================================================
-- Section 1: tables, columns, logins and roles, closed days
